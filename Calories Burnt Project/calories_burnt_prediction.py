#Importing the dependencies
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from xgboost import XGBRegressor
from sklearn import metrics

#import Data
calories_burnt_dataset = pd.read_csv('/content/calories.csv')

calories_burnt_dataset.head()

calories_burnt_dataset.shape

calories_burnt_dataset.isnull().sum()

calories_burnt_dataset.describe()

exercise_dataset = pd.read_csv('/content/exercise.csv')

exercise_dataset.head()

exercise_dataset.shape

exercise_dataset.isnull().sum()

exercise_dataset.describe()

calories_burnt_dataset = pd.concat([exercise_dataset,calories_burnt_dataset['Calories']],axis = 1)
calories_burnt_dataset.head()

calories_burnt_dataset.shape

calories_burnt_dataset.info()

calories_burnt_dataset.isnull().sum()

calories_burnt_dataset.describe()

import seaborn as sns
sns.set()

sns.countplot(x = 'Gender',data = calories_burnt_dataset)

sns.distplot(calories_burnt_dataset['Age'])

sns.distplot(calories_burnt_dataset['Height'])

sns.distplot(calories_burnt_dataset['Weight'])

#Finding the correlation in the dataset
import matplotlib.pyplot as plt

correlation = calories_burnt_dataset.drop('Gender', axis=1).corr()
plt.figure(figsize=(8,8))
sns.heatmap(correlation,cbar = True,square = True,fmt = '.1f',annot = True,annot_kws = {'size':8},cmap = 'Blues')

#Converting the data numerical values
calories_burnt_dataset.replace({'Gender':{'male':0,'female':1}},inplace = True)

calories_burnt_dataset.head()

#Separating feaures and target
X = calories_burnt_dataset.drop(columns = ['User_ID','Calories'],axis = 1)
Y = calories_burnt_dataset['Calories']

print(X)
print(Y)

#Traing and split data
X_train,X_test,Y_train,Y_test = train_test_split(X,Y,test_size = 0.2,random_state = 2)

print(X.shape,X_train.shape,X_test.shape)

#Model apply
regression = XGBRegressor()
regression.fit(X_train,Y_train)

X_train_prediction = regression.predict(X_train)
print(X_train_prediction)

test_prediction = regression.predict(X_test)
print(test_prediction)

#Mean aAbsulate Error
mae = metrics.mean_absolute_error(Y_test,test_prediction)
print('Mean Absulate Error',mae)

